# Build the publishable snapshot branch.
#
# The development history stays private. This writes a single snapshot commit
# on `refs/heads/public` holding the current tree minus everything named in
# tools/publish/publicignore, with tools/publish/overrides/* substituted in.
# The first run has no parent, so the published branch begins with no history;
# later runs append one snapshot commit each, so the remote is never rewritten.
#
# Nothing here touches the working tree, the index, or HEAD: the snapshot is
# assembled in a temporary index with plumbing. It is therefore safe to run
# while other work is in progress in this checkout.
#
# Before the branch moves, the snapshot itself is verified, because the
# published tree is not the development tree: it lacks the planning documents
# and its citations are rewritten, so a gate can pass here and fail there. The
# snapshot is extracted into a fresh directory under --work-dir, built in
# Release with warnings as errors, and its complete CTest suite must pass (the
# timing-bound pty label may take one retry, as in CI). When ckdocs is on
# PATH, the documentation site must also build with --strict. A failure
# leaves the branch untouched and keeps the directory for inspection; a
# success removes it.
#
#   tools/publish/make-public.sh                  # snapshot HEAD onto `public`
#   tools/publish/make-public.sh --dry-run        # list what would be included
#   tools/publish/make-public.sh -m "Release 0.1"
#   tools/publish/make-public.sh --work-dir /Volumes/scratch --jobs 8
#
# --evidence-dir retains logs and an input/output build receipt before cleanup.
# --work-dir defaults to $TMPDIR; --jobs to the processor count.
#
# Then, once:  git remote add origin https://github.com/<owner>/<repo>.git
# And to push: git push -u origin public:main

set -eu

root=$(git rev-parse --show-toplevel)
cd "$root"

source_rev=HEAD
branch=public
message=
dry_run=0
work_root=${TMPDIR:-}
evidence_dir=
jobs=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)

while [ $# -gt 0 ]; do
    case $1 in
        --source) source_rev=$2; shift 2 ;;
        --branch) branch=$2; shift 2 ;;
        -m|--message) message=$2; shift 2 ;;
        -n|--dry-run) dry_run=1; shift ;;
        --work-dir) work_root=$2; shift 2 ;;
        --jobs) jobs=$2; shift 2 ;;
        --evidence-dir) evidence_dir=$2; shift 2 ;;
        -h|--help) sed -n '5,35p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "make-public: unknown argument: $1" >&2; exit 2 ;;
    esac
done
case $jobs in ''|*[!0-9]*|0) echo "make-public: --jobs needs a positive number" >&2; exit 2 ;; esac
[ -n "$work_root" ] || { echo "make-public: set TMPDIR or pass --work-dir" >&2; exit 2; }
[ -d "$work_root" ] || { echo "make-public: --work-dir $work_root is not a directory" >&2; exit 2; }

ignore_file=tools/publish/publicignore
overrides_dir=tools/publish/overrides
[ -f "$ignore_file" ] || { echo "make-public: missing $ignore_file" >&2; exit 1; }

src_commit=$(git rev-parse --verify "$source_rev^{commit}")
[ -n "$message" ] || message="Snapshot of $(git rev-parse --short "$src_commit")"

# A path is excluded when it equals an entry in publicignore, or lies under an
# entry that names a directory. Comments and blank lines are dropped.
filter_paths() {
    awk -v ignore="$ignore_file" '
        BEGIN {
            while ((getline line < ignore) > 0) {
                sub(/[ \t]+$/, "", line)
                if (line == "" || line ~ /^#/) continue
                patterns[++n] = line
            }
        }
        {
            path = $0
            sub(/^[^\t]*\t/, "", path)          # ls-tree: "<mode> <type> <sha>\t<path>"
            for (i = 1; i <= n; i++) {
                p = patterns[i]
                if (substr(p, length(p)) == "/") {
                    if (index(path, p) == 1) next
                } else if (path == p) {
                    next
                }
            }
            print
        }'
}

index=$(mktemp "${work_root}/make-public-index.XXXXXX")
rm -f "$index"                                   # git wants to create it itself
trap 'rm -f "$index"' EXIT INT TERM
export GIT_INDEX_FILE="$index"

all_paths=$(git ls-tree -r --full-tree "$src_commit")
git ls-tree -r --full-tree "$src_commit" | filter_paths | git update-index --index-info

# Overrides: a file at tools/publish/overrides/<path> replaces <path> in the
# snapshot. This is how the public README differs from the working one without
# either copy having to be regenerated by hand.
overrides=
if [ -d "$overrides_dir" ]; then
    overrides=$(cd "$overrides_dir" && find . -type f | sed 's|^\./||' | sort)
    for rel in $overrides; do
        blob=$(git hash-object -w "$overrides_dir/$rel")
        git update-index --add --cacheinfo "100644,$blob,$rel"
    done
fi

# The comments cite documents this snapshot does not carry. derefer.py replaces
# each path with the document's name in prose, in the snapshot's blobs only, so
# the reasoning survives publication and the dangling pointer does not. It works
# on comments and markdown; a string literal is code and is never touched.
deref_report=
if [ -x tools/publish/derefer.py ]; then
    deref_report=$(python3 tools/publish/derefer.py) || {
        echo "make-public: derefer.py failed — refusing to publish" >&2
        exit 1
    }
fi

kept=$(git ls-files | wc -l | tr -d ' ')
total=$(printf '%s\n' "$all_paths" | wc -l | tr -d ' ')

if [ "$dry_run" -eq 1 ]; then
    echo "source:    $(git rev-parse --short "$src_commit") ($source_rev)"
    echo "branch:    $branch (not written — dry run)"
    echo "included:  $kept of $total tracked paths"
    [ -n "$deref_report" ] && echo "citations: ${deref_report#derefer: }"
    echo
    echo "excluded:"
    printf '%s\n' "$all_paths" | sed 's/^[^\t]*\t//' | sort > "$index.all"
    git ls-files | sort > "$index.kept"
    comm -23 "$index.all" "$index.kept" | sed 's/^/  - /'
    rm -f "$index.all" "$index.kept"
    [ -n "$overrides" ] && { echo; echo "overridden:"; printf '%s\n' "$overrides" | sed 's/^/  ~ /'; }
    exit 0
fi

tree=$(git write-tree)

parent=
if parent=$(git rev-parse -q --verify "refs/heads/$branch"); then
    if [ "$(git rev-parse "$parent^{tree}")" = "$tree" ]; then
        echo "make-public: $branch is already this snapshot — nothing to do."
        exit 0
    fi
fi

# Verify the snapshot tree exactly as it will be published (see the header).
verify_dir=$(mktemp -d "$work_root/make-public-verify.XXXXXX")
verify_step() {
    step=$1
    log="$verify_dir/$step.log"
    shift
    echo "make-public: verifying the snapshot: $step"
    if ! "$@" >"$log" 2>&1; then
        tail -n 30 "$log" >&2
        echo "make-public: the snapshot failed its $step step — $branch not moved." >&2
        echo "make-public: logs and build kept in $verify_dir" >&2
        exit 1
    fi
}
check_no_warnings() {
    if grep -n "warning:" "$verify_dir/build.log" >&2; then
        return 1
    fi
}
git archive "$tree" | (mkdir "$verify_dir/src" && cd "$verify_dir/src" && tar -xf -)
mkdir -p "$verify_dir/test-tmp"
verify_step configure cmake -S "$verify_dir/src" -B "$verify_dir/build" \
    -DCMAKE_BUILD_TYPE=Release -DCKVISION_WARNINGS_AS_ERRORS=ON \
    "-DCKVISION_TEST_TEMP_ROOT=$verify_dir/test-tmp"
if [ -n "$evidence_dir" ]; then
    verify_step build python3 "$verify_dir/src/tools/ci/build_monitor.py" \
        --source "$verify_dir/src" --build "$verify_dir/build" \
        --executable "$verify_dir/build/examples/ckvision_gallery" \
        --record "$verify_dir/build-record.json" --jobs "$jobs"
else
    verify_step build cmake --build "$verify_dir/build" --parallel "$jobs"
fi
verify_step warnings check_no_warnings
verify_step test ctest --test-dir "$verify_dir/build" --output-on-failure --parallel "$jobs" -LE pty
verify_step pty ctest --test-dir "$verify_dir/build" --output-on-failure --parallel "$jobs" -L pty --repeat until-pass:2
if command -v ckdocs >/dev/null 2>&1; then
    verify_step docs ckdocs build --root "$verify_dir/src" --out "$verify_dir/site" --strict
    site_note="ckdocs --strict site built"
else
    site_note="ckdocs not on PATH: the documentation site was not built"
    echo "make-public: $site_note" >&2
fi
suite_count() { sed -n 's/.*tests passed.* out of \([0-9][0-9]*\).*/\1/p' "$1" | tail -n 1; }
tests_passed="$(suite_count "$verify_dir/test.log") tests and $(suite_count "$verify_dir/pty.log") pty tests passed"
if [ -n "$evidence_dir" ]; then
    mkdir -p "$evidence_dir"
    cp "$verify_dir/"*.log "$verify_dir/build-record.json" "$evidence_dir/"
    printf 'source=%s\ntree=%s\n%s\n%s\n' "$src_commit" "$tree" "$tests_passed" "$site_note" > "$evidence_dir/snapshot.txt"
fi
rm -rf "$verify_dir"

if [ -n "$parent" ]; then
    commit=$(git commit-tree "$tree" -p "$parent" -m "$message")
else
    commit=$(git commit-tree "$tree" -m "$message")
fi

git update-ref "refs/heads/$branch" "$commit"

echo "make-public: $branch -> $(git rev-parse --short "$commit")"
echo "  source:   $(git rev-parse --short "$src_commit") ($source_rev)"
echo "  included: $kept of $total tracked paths"
[ -n "$deref_report" ] && echo "  citations: ${deref_report#derefer: }"
echo "  verified: Release, warnings as errors; $tests_passed; $site_note"
echo "  message:  $message"
echo
echo "Review it with:  git show --stat $branch"
echo "Publish it with: git push origin $branch:main"
